import type { Business, BusinessHours, DayOfWeek } from "@/lib/types";

const createWeeklyHours = (
  weekdayOpen: string,
  weekdayClose: string,
  weekendOpen: string,
  weekendClose: string,
  closedDays: DayOfWeek[] = []
): BusinessHours[] => {
  const days: DayOfWeek[] = [
    "monday",
    "tuesday",
    "wednesday",
    "thursday",
    "friday",
    "saturday",
    "sunday",
  ];

  return days.map((day) => {
    const isWeekend = day === "saturday" || day === "sunday";
    const isClosed = closedDays.includes(day);

    return {
      day,
      open: isWeekend ? weekendOpen : weekdayOpen,
      close: isWeekend ? weekendClose : weekdayClose,
      closed: isClosed,
    };
  });
};

